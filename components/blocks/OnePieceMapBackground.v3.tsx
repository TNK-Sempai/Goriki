function CompassPoints({
  rotate,
  long,
  short,
  half,
  fill,
  opacity,
}: {
  rotate?: number
  long: number
  short: number
  half: number
  fill: string
  opacity: number
}) {
  return (
    <g fill={fill} opacity={opacity} transform={rotate ? `rotate(${rotate})` : undefined}>
      <path d={`M0 ${-long}L${half} ${-short}L0 0L${-half} ${-short}z`} />
      <path d={`M0 ${long}L${half} ${short}L0 0L${-half} ${short}z`} />
      <path d={`M${-long} 0L${-short} ${-half}L0 0L${-short} ${half}z`} />
      <path d={`M${long} 0L${short} ${-half}L0 0L${short} ${half}z`} />
    </g>
  )
}

